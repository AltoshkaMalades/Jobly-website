#!/bin/bash
################################################################################
# Backup and Migration Script
# 
# Функция: Создает бэкап БД перед миграциями для безопасности
# Использование: bash scripts/backup_and_migrate.sh
# 
# Параметры окружения:
#   - DATABASE_URL: URL базы данных (обязателен для бэкапа)
#   - BACKUP_DIR: Папка для сохранения бэкапов (default: backups/)
#   - RETENTION_DAYS: Сохранять бэкапы N дней (default: 7)
################################################################################

set -euo pipefail

# ============================================================================
# КОНФИГУРАЦИЯ
# ============================================================================
BACKUP_DIR="${BACKUP_DIR:-backups}"
RETENTION_DAYS="${RETENTION_DAYS:-7}"
DB_URL="${DATABASE_URL:-}"
TIMESTAMP=$(date +%Y-%m-%d_%H-%M-%S)
BACKUP_FILE="${BACKUP_DIR}/backup_${TIMESTAMP}.sql"

# Цвета для вывода
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# ============================================================================
# ФУНКЦИИ
# ============================================================================

log_info() {
    echo -e "${GREEN}✅${NC} $1"
}

log_warn() {
    echo -e "${YELLOW}⚠️${NC} $1"
}

log_error() {
    echo -e "${RED}❌${NC} $1"
}

# ============================================================================
# ГЛАВНАЯ ЛОГИКА
# ============================================================================

echo "=========================================="
echo "🔄 Backup & Migration Script"
echo "=========================================="

# Проверка pg_dump
if ! command -v pg_dump >/dev/null 2>&1; then
    log_error "pg_dump не найден. Установите PostgreSQL client tools."
    exit 1
fi

# Создание папки для бэкапов
mkdir -p "$BACKUP_DIR"

# ============================================================================
# ШАГ 1: БЭКАП БАЗЫ ДАННЫХ
# ============================================================================

echo ""
echo "📦 ШАГ 1: Создание бэкапа базы данных..."

if [ -z "$DB_URL" ]; then
    log_warn "DATABASE_URL не установлен - пропускаем бэкап"
    log_info "Если нужен бэкап, установите: export DATABASE_URL='...'"
else
    echo "   Использую: ${DB_URL%%@*}@***"
    echo "   Сохраняю в: $BACKUP_FILE"
    
    if pg_dump "$DB_URL" > "$BACKUP_FILE"; then
        BACKUP_SIZE=$(du -h "$BACKUP_FILE" | cut -f1)
        log_info "Бэкап создан успешно (размер: $BACKUP_SIZE)"
        log_info "Файл: $BACKUP_FILE"
    else
        log_error "Ошибка при создании бэкапа!"
        exit 1
    fi
    
    # Очистка старых бэкапов
    echo ""
    echo "🗑️  Удаление старых бэкапов (старше $RETENTION_DAYS дней)..."
    OLD_BACKUPS=$(find "$BACKUP_DIR" -name "backup_*.sql" -mtime +$RETENTION_DAYS 2>/dev/null | wc -l)
    
    if [ "$OLD_BACKUPS" -gt 0 ]; then
        find "$BACKUP_DIR" -name "backup_*.sql" -mtime +$RETENTION_DAYS -delete
        log_info "Удалено старых бэкапов: $OLD_BACKUPS"
    else
        log_warn "Нет старых бэкапов для удаления"
    fi
fi

# ============================================================================
# ШАГ 2: ЗАПУСК МИГРАЦИЙ
# ============================================================================

echo ""
echo "🚀 ШАГ 2: Запуск Django миграций..."

if python manage.py migrate --noinput; then
    log_info "Django миграции выполнены успешно"
else
    log_error "Ошибка при выполнении Django миграций!"
    exit 1
fi

# ============================================================================
# ШАГ 3: ЗАПУСК ALEMBIC МИГРАЦИЙ (ОПЦИОНАЛЬНО)
# ============================================================================

echo ""
echo "🔄 ШАГ 3: Проверка Alembic миграций (опционально)..."

if [ -f "alembic.ini" ] && command -v alembic >/dev/null 2>&1; then
    if alembic upgrade head; then
        log_info "Alembic миграции выполнены успешно"
    else
        log_warn "Alembic миграции пропущены или не требуются"
    fi
else
    log_warn "Alembic не найден или не настроен - пропускаем"
fi

# ============================================================================
# ШАГ 4: СБОР СТАТИЧЕСКИХ ФАЙЛОВ (ОПЦИОНАЛЬНО)
# ============================================================================

echo ""
echo "📂 ШАГ 4: Сбор статических файлов (опционально)..."

if python manage.py collectstatic --noinput 2>/dev/null; then
    log_info "Статические файлы собраны успешно"
else
    log_warn "Сбор статических файлов пропущен (не критично)"
fi

# ============================================================================
# ИТОГИ
# ============================================================================

echo ""
echo "=========================================="
log_info "Все шаги выполнены успешно!"
echo "=========================================="
echo ""
echo "📊 Резюме:"
echo "   • Бэкап: $([ -z "$DB_URL" ] && echo "пропущен" || echo "$BACKUP_FILE")"
echo "   • Django миграции: ✅"
echo "   • Alembic миграции: ✅ (если используется)"
echo "   • Статические файлы: ✅ (если используется)"
echo ""
log_info "Приложение готово к работе!"
